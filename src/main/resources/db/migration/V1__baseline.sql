-- V1: schema as it was before Flyway (16/10/2026), dumped with pg_dump -s from the shared Render DB.
-- On that DB Flyway only records this version (baseline-on-migrate); on an empty DB it creates everything.
-- Object names are not schema-qualified (created in the current schema); PostGIS types come from public.
CREATE EXTENSION IF NOT EXISTS postgis;
-- Accent-insensitive search: unaccent('Cần Thơ') = 'Can Tho'
CREATE EXTENSION IF NOT EXISTS unaccent;

CREATE TABLE accounts (
    account_id uuid NOT NULL,
    address text,
    agency_type character varying(30),
    created_date timestamp(6) without time zone,
    email character varying(100) NOT NULL,
    first_name character varying(100),
    is_active boolean NOT NULL,
    is_dispatcher boolean DEFAULT false NOT NULL,
    is_locked boolean NOT NULL,
    last_name character varying(100),
    password character varying(255) NOT NULL,
    phone character varying(10),
    province character varying(150),
    ward character varying(150),
    role_id bigint NOT NULL,
    unit_level character varying(20),
    CONSTRAINT accounts_unit_level_check CHECK (((unit_level)::text = ANY ((ARRAY['NATIONAL'::character varying, 'PROVINCE'::character varying, 'WARD'::character varying])::text[])))
);

CREATE TABLE incident_claims (
    id bigint NOT NULL,
    claimed_at timestamp(6) without time zone NOT NULL,
    end_reason character varying(20),
    note character varying(255),
    released_at timestamp(6) without time zone,
    account_id uuid NOT NULL,
    handed_to_id uuid,
    incident_id character varying(50) NOT NULL
);

ALTER TABLE incident_claims ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME incident_claims_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

CREATE TABLE incidents (
    id character varying(50) NOT NULL,
    accuracy integer,
    address text,
    assigned_dispatcher character varying(100),
    assigned_station_id bigint,
    audio_url text,
    citizen_name character varying(150),
    citizen_token_hash character varying(64),
    created_at timestamp(6) without time zone NOT NULL,
    description text,
    emergency_type character varying(30) NOT NULL,
    incident_tags jsonb,
    latitude double precision,
    location public.geometry(Point,4326),
    longitude double precision,
    media jsonb,
    phone character varying(10),
    province character varying(150),
    status character varying(30) NOT NULL,
    transcript text,
    updated_at timestamp(6) without time zone,
    ward character varying(150),
    accepted_at timestamp(6) without time zone,
    claimed_at timestamp(6) without time zone,
    escalate_at timestamp(6) without time zone,
    escalated_at timestamp(6) without time zone,
    handler_id uuid,
    routed_agency character varying(30),
    routed_level character varying(20),
    cancel_reason character varying(30),
    cancelled_at timestamp(6) without time zone
);

CREATE TABLE provinces (
